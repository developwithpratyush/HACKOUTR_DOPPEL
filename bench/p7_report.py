"""Render docs/eval/p7-risk-model.md from p7-leakage.json and p7-risk-model.json (run both producers first).

    .venv/Scripts/python.exe bench/p7_leakage.py
    .venv/Scripts/python.exe -m doppel.risk.train
    .venv/Scripts/python.exe bench/p7_report.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from doppel.contract import REPO_ROOT  # noqa: E402

EVAL = REPO_ROOT / "docs" / "eval"
KIND_NAMES = {"benign": "Benign NRD names (no brand signal)", "hard_negative": "Hard negatives (popular real domains like a brand)",
              "genuine": "Genuine family names"}


def pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def n(x: int) -> str:
    return f"{x:,}"


def main() -> int:
    leak = json.loads((EVAL / "p7-leakage.json").read_text(encoding="utf-8"))
    rm = json.loads((EVAL / "p7-risk-model.json").read_text(encoding="utf-8"))
    d = rm["data"]
    ship = rm["held_out"][0]
    legit = rm["phiusiil_test_by_label"]["legitimate"]
    phish = rm["phiusiil_test_by_label"]["phishing"]
    nrd = rm["shift"]["nrd"]
    p3 = rm["shift"]["p3"]
    real = p3["test_real"]
    L = []
    w = L.append

    w("# P7: Risk Model (C8): leakage audit, host-only model, distribution shift")
    w("")
    w(f"*Generated by `bench/p7_report.py` from `p7-leakage.json` ({leak['generated_at']}) and "
      f"`p7-risk-model.json` ({rm['generated_at']}). Model `{rm['model_version']}`, seed {rm['seed']}.*")
    w("")
    w("**In one paragraph.** On PhiUSIIL, a model reaches "
      f"**{pct(leak['ablation'][0]['accuracy'])}** accuracy, but only because the columns give the answer away. "
      "Restricted to what a bare new domain actually has (its name), the honest number on hosts split by "
      f"registrable domain is **{pct(ship['accuracy'])} accuracy, ROC-AUC {ship['roc_auc']:.3f}**. "
      f"And on real new domains the model is badly shifted: it scores **{pct(nrd['share_ge_0.5'])}** of NRD names "
      f"at 0.5 or more, against {pct(legit['share_ge_0.5'])} of PhiUSIIL's legitimate hosts. So Doppel uses it as "
      "one **weak, supporting** signal (at most ±0.5 log-odds) that never decides a verdict.")
    w("")
    w("---")
    w("")
    w("## 1. Why \"99.9%\" isn't real: the leakage audit")
    w("")
    w(f"Same model for every row ({leak['model']}), PhiUSIIL rows ({n(leak['rows'])}, "
      f"{pct(leak['phishing_share'])} phishing), 80/20 split. \"Split by registrable domain\" keeps every row of an "
      "ICANN-level registrable domain on one side.")
    w("")
    w("| Setting | Columns | Accuracy | ROC-AUC |")
    w("|---|---|---|---|")
    for a in leak["ablation"]:
        w(f"| {a['setting']} | {a['columns']} | {pct(a['accuracy'])} | {a['roc_auc']:.4f} |")
    w(f"| **Doppel's host-only model** (shipped: the host's own name, `www.` stripped; unique hosts, split by "
      f"registrable domain) | n-grams + {len(rm['top_weights'])} stats | **{pct(ship['accuracy'])}** | "
      f"**{ship['roc_auc']:.4f}** |")
    w("")
    w("The last row counts unique hosts (one row per host), the others count URLs (phishing hosts repeat ~1.2×). "
      "The point is the order of magnitude: from \"perfect\" to \"useful but limited\".")
    w("")
    w(f"### Single-feature ROC-AUC (top 15 of {len(leak['columns'])})")
    w("")
    w("Oriented so 0.5 = useless and 1.0 = a perfect giveaway. **Available for a bare domain?** A name from an NRD "
      "feed or a CT log has no page, no scheme or path, and none of the dataset-derived statistics.")
    w("")
    w("| Column | AUC | Kind | Leaky (> 0.98) |")
    w("|---|---|---|---|")
    for c in leak["columns"][:15]:
        w(f"| `{c['column']}` | {c['auc']:.4f} | {c['kind']}: {leak['kinds'][c['kind']]} | {'**yes**' if c['leaky'] else ''} |")
    w("")
    w("Probes for dataset artifacts (not columns):")
    w("")
    w("| Probe | AUC | Legitimate rows | Phishing rows |")
    w("|---|---|---|---|")
    for a in leak["artifacts"]:
        w(f"| {a['probe']} | {a['auc']:.4f} | {pct(a['share_legitimate'])} | {pct(a['share_phishing'])} |")
    w("")
    w("**What the audit found:**")
    w("")
    w(f"- The single-feature rule (drop AUC > {leak['leak_auc_threshold']}) removes only "
      f"{len(leak['leaky'])} columns ({', '.join('`' + c + '`' for c in leak['leaky'])}), and accuracy stays at "
      f"{pct(leak['ablation'][2]['accuracy'])}. **The leak lives in combinations**, not single columns: \"the URL "
      "starts with `https://www.`\" is true for 100% of legitimate rows and ~2% of phishing rows, yet no single "
      "column holds it (`IsHTTPS` alone is 0.75, the `www.` alone 0.79).")
    w("- So the rule that matters is the second one in BUILD_PHASES: *drop anything unavailable for a bare new "
      f"domain*. With PhiUSIIL's own host columns ({', '.join('`' + c + '`' for c in leak['host_columns_used'])}) "
      f"accuracy falls to {pct(leak['ablation'][-1]['accuracy'])}; they still count the `www.` every legitimate row has.")
    w("- Punycode isn't a signal here only because there's almost none of it (0 legitimate IDNs, 0.15% of phishing). "
      "The model folds look-alike letters to ASCII so it can't learn \"has xn-- = phishing\"; hidden letters are C3's job.")
    w("")
    w("## 2. The shipped model")
    w("")
    w("| Step | What we did | Why |")
    w("|---|---|---|")
    w(f"| Unit | One row per **host** ({n(d['unique_hosts'])} unique hosts from {n(d['phiusiil_rows'])} URLs) | "
      "A new domain has one name; repeated URLs on one host would weight it many times |")
    w("| Host | Scheme, path, port and a leading `www.` stripped; IDNA-decoded; look-alike letters folded to ASCII | "
      "Removes the `https://www.` and punycode artifacts |")
    w(f"| Conflicts | {d['conflicted_hosts_dropped']} hosts labelled both ways dropped (e.g. "
      f"{', '.join('`' + h + '`' for h in d['conflicted_examples'][:4])}) | The trick is in the path (open redirects, "
      "shared hosts, O2): a host-only model can't separate them |")
    w(f"| Kept out | {d['kept_out_in_pairs']} hosts that appear in `data/pairs/pairs.csv` | The P3 evaluation "
      "(incl. `test_real`, which *is* PhiUSIIL phishing) stays clean |")
    w(f"| Split | By ICANN registrable domain: train {n(d['train_hosts'])} hosts / {n(d['train_groups'])} domains, "
      f"held-out {n(d['test_hosts'])} / {n(d['test_groups'])} | No owner on both sides; every `*.web.app` host "
      "on one side |")
    w("| Features | Character 3–5-grams of `<host>` (TF-IDF, sublinear tf, hashed into 2^18 buckets with CRC-32), a "
      "`tld=` token, and 12 lexical stats (length, labels, subdomain depth, name length, digit share, hyphens, "
      "entropy, vowel share, digit run, consonant run, longest label, IP) | Host only; the TLD as a one-hot token "
      "is target encoding without fold leakage |")
    w(f"| Model | Logistic regression (liblinear), C = {rm['chosen_C']} chosen by 5-fold GroupKFold out-of-fold "
      "log-loss | Explainable per feature (the evidence names what pushed it); tiny; pure-Python inference |")
    w("| Calibration | Isotonic regression on the out-of-fold scores of the chosen C | Probabilities that hold on "
      "the held-out split (section 3) |")
    w(f"| Export | `doppel/risk/model/risk_model.json` + `ngram.f32.gz` (idf + weights, float32) | The brain needs "
      f"no numpy or scikit-learn. Parity with scikit-learn on {n(rm['parity']['hosts'])} held-out hosts: max "
      f"difference {rm['parity']['max_abs_diff']:.6f} |")
    w("")
    w("C tuning (out of fold, train split):")
    w("")
    w("| C | ROC-AUC | Log-loss | Accuracy |")
    w("|---|---|---|---|")
    for t in rm["tuning"]:
        mark = " (chosen)" if t["C"] == rm["chosen_C"] else ""
        w(f"| {t['C']}{mark} | {t['roc_auc']:.4f} | {t['log_loss']:.4f} | {pct(t['accuracy'])} |")
    w("")
    w(f"**Held-out split** ({n(ship['n'])} hosts, {pct(d['test_phishing_share'])} phishing):")
    w("")
    w("| Model | ROC-AUC | Accuracy | Brier | Phishing caught at 0.5 | Legitimate flagged at 0.5 |")
    w("|---|---|---|---|---|---|")
    for m in rm["held_out"]:
        w(f"| {m['name']} | {m['roc_auc']:.4f} | {pct(m['accuracy'])} | {m['brier']:.4f} | {pct(m['tpr_at_0.5'])} | "
          f"{pct(m['fpr_at_0.5'])} |")
    w(f"| Shipped model *before* calibration | {ship['uncalibrated']['roc_auc']:.4f} | "
      f"{pct(ship['uncalibrated']['accuracy'])} | {ship['uncalibrated']['brier']:.4f} | "
      f"{pct(ship['uncalibrated']['tpr_at_0.5'])} | {pct(ship['uncalibrated']['fpr_at_0.5'])} |")
    w("")
    w("Lexical-stat weights (standardised features; positive = towards phishing): " +
      ", ".join(f"{t['feature']} {t['weight']:+.2f}" for t in rm["top_weights"]) + ".")
    w("")
    w(f"Speed: **{nrd['per_name_us']:.0f} µs per name** in pure Python (NRD sample, one core), so it adds well under "
      "a millisecond to an investigation.")
    w("")
    w("## 3. Reliability")
    w("")
    w("![Reliability and score distributions](p7-reliability.png)")
    w("")
    w("| Bin | PhiUSIIL held-out: n | mean p | observed phishing | P3 pairs: n | mean p | observed look-alike |")
    w("|---|---|---|---|---|---|---|")
    p3bins = {tuple(b["bin"]): b for b in rm["reliability"]["p3_test"]}
    for b in rm["reliability"]["phiusiil_test"]:
        o = p3bins.get(tuple(b["bin"]))
        tail = f"{n(o['n'])} | {o['mean_p']:.3f} | {pct(o['observed'])}" if o else "0 | | "
        w(f"| {b['bin'][0]:.1f}–{b['bin'][1]:.1f} | {n(b['n'])} | {b['mean_p']:.3f} | {pct(b['observed'])} | {tail} |")
    w("")
    w(f"In distribution the calibrated probability is honest (Brier {ship['brier']:.3f}). It is calibrated to "
      f"PhiUSIIL's base rate (**{pct(d['train_phishing_share'])} phishing**), which is nothing like the share of "
      "phishing among real new domains. On the P3 pairs the curve leaves the diagonal: the same number means "
      "something else on a different population.")
    w("")
    w("## 4. Distribution shift (the honest weakness)")
    w("")
    w("| Population | Names | Mean ML risk | ≥ 0.5 | ≥ 0.8 | ≥ 0.9 |")
    w("|---|---|---|---|---|---|")
    rows = [("PhiUSIIL legitimate (held-out)", legit), ("PhiUSIIL phishing (held-out)", phish),
            (f"**NRD 7-day snapshot** (every {nrd['sample_every']}th name, unlabelled)", nrd)]
    rows += [(KIND_NAMES.get(k, k), v) for k, v in p3["by_kind"].items() if not k.startswith("lookalike")]
    rows += [(f"P3 look-alikes, {k.split(' ', 1)[1]}", v) for k, v in p3["by_kind"].items() if k.startswith("lookalike")]
    rows += [("Real brand phish (`test_real`, PhiUSIIL rows kept out of training)", real)]
    for name, s in rows:
        w(f"| {name} | {n(s['n'])} | {s['mean_p']:.3f} | {pct(s['share_ge_0.5'])} | {pct(s['share_ge_0.8'])} | "
          f"{pct(s['share_ge_0.9'])} |")
    w("")
    w(f"P3 held-out pairs, look-alike vs not: ROC-AUC **{p3['overall']['roc_auc']:.3f}** "
      f"(vs {ship['roc_auc']:.3f} in distribution).")
    w("")
    w("**What this means:**")
    w("")
    w(f"- **New domains look like PhiUSIIL phishing.** PhiUSIIL's legitimate rows are established, popular homepages; "
      f"a brand-new name is long, random-looking or on an unusual ending far more often, so "
      f"{pct(nrd['share_ge_0.5'])} of NRD names score ≥ 0.5. Used alone as a classifier on new domains, it would "
      "bury analysts in false alarms. That's the main reason it's weak evidence.")
    w("- **It is blind to look-alikes by construction.** It never sees the brand list. A one-letter swap of a short "
      "`.com` (`paytrn.com`) reads as an ordinary site; the T1/T2/T3/T12/T13 rows above show it. Catching those is the "
      "Trick Detector's job (P4: 73–99% right-brand detection on the same held-out pairs).")
    w("- **It does see the generic phishing shape**: brand + lure words, hyphens, rebuilt trust endings (T4, T7 score "
      f"high), and it flags {pct(real['share_ge_0.5'])} of the real brand phish whose hosts it never trained on. That "
      "last number is *not* a shift test: those rows come from PhiUSIIL itself. What it adds to Doppel is a second "
      "opinion on names with *no* brand, e.g. a brand-less clone's address.")
    sub_w = next(t["weight"] for t in rm["top_weights"] if t["feature"] == "sub_depth")
    w(f"- **\"Has subdomains\" is partly an artifact.** Subdomain depth is the heaviest lexical weight ({sub_w:+.2f}). "
      "Once `www.` is stripped, PhiUSIIL's legitimate homepages never have subdomains, so level-squats and free-hosting "
      "users (T6, T11) score ~100%, but so would a legitimate `login.example.com`. The Address Reader already names "
      "those owners exactly (C1), which is why C8 stays weak.")
    w("- **Hard negatives and genuine names** (popular real domains) mostly score low, as PhiUSIIL's legitimate rows do; "
      "the genuine names that score high are the ones with subdomains (H1 decides those anyway, and C8 doesn't run).")
    w("")
    w("## 5. How Doppel uses it")
    w("")
    w("- Tool `risk_model`, criterion **C8**, Standard stage, in parallel with the Human-Eye Renderer and the Page "
      "Probe. Skipped for proven family members (H1 decides them) and for batch names that stop after Quick.")
    w("- One `ml_risk` evidence item, always **weak**: p ≥ 0.6 → phishing (score p), p ≤ 0.4 → genuine (score 1 − p), "
      "in between → neutral (no opinion). Fusion v1 adds `0.5 × (2·score − 1)` log-odds, so at most ±0.5, "
      "continuous at 0.5.")
    w("- The evidence names the n-grams, ending and lexical stats that pushed it (`details.top_features`), and the "
      "base rate it's calibrated to, so the Explorer can show *why* without overclaiming.")
    w("- Gallery labels are unchanged by it (6/7 match the mocks; 05 still needs Deep). A name alone still never "
      "reaches PHISHING.")
    w("")
    w("## 6. Limitations and plans")
    w("")
    w("| Limitation | Plan |")
    w("|---|---|")
    w("| Trained on popular homepages vs phishing URLs: shifted on new domains (section 4) | P11 learns its weight in "
      "the combiner on the P3 train split, so the shift is priced in; a better negative class (random NRD names "
      "aged 30+ days without abuse reports) would fix the root cause |")
    w("| Legitimate training rows are homepages only, so subdomains read as risky | Add legitimate subdomain hosts "
      "(e.g. CT-log names under established domains) as negatives and retrain |")
    w("| Calibrated to a ~38% phishing base rate | Never shown as a real-world probability; P11's combiner and its "
      "reliability chart on held-out data state the base rate |")
    w("| Overlaps C6 (ending risk) and C1 (free hosting), which also come from PhiUSIIL / the PSL | Both weak; "
      "fusion counts the strongest item per criterion; P11's learned weights handle the correlation |")
    w("| PhiUSIIL is a fixed snapshot (published 2024); phishing names drift | Retrain from fresh feeds; `python -m doppel.risk.train` "
      "rebuilds everything in a few minutes |")
    w("")
    w("## Reproduce")
    w("")
    w("```bash")
    w(".venv/Scripts/python.exe -m pip install -e \".[dev,tricks,risk,bench]\"")
    w(".venv/Scripts/python.exe bench/p7_leakage.py        # ~20 s  -> p7-leakage.json")
    w(f".venv/Scripts/python.exe -m doppel.risk.train      # ~{rm['seconds'] / 60:.0f} min -> model + p7-risk-model.json + p7-reliability.png")
    w(".venv/Scripts/python.exe bench/p7_report.py         # this file")
    w("```")
    w("")
    (EVAL / "p7-risk-model.md").write_text("\n".join(L), encoding="utf-8", newline="\n")
    print(f"wrote {EVAL / 'p7-risk-model.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
