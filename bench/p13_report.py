"""P13 eval: docs/eval/p13-campaigns.md from data/campaigns/radar.json, docs/eval/p13-conformal.json and the
hand-check below (names only; nothing was visited).

    python -m doppel.cli campaigns --raw data/raw/nrd/nrd7.txt:nrd --raw data/raw/phishing_database/phishing-domains-ACTIVE.txt:pdb
    python bench/p13_conformal.py
    python bench/p13_report.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]

# Hand-check of the top 10 campaigns (2026-11-06), by campaign id. "pure" = every member plausibly one maker.
HANDCHECK = {
    "C2ecb3504": ("pure", "12/12 `indiapost.gov.<random>.top`, all on Phishing.Database ACTIVE (confirmed phishing). One template, one ending."),
    "Cd40e4c46": ("pure, one operator (proven)", "Template `in-<B>` (`ln-` folded), the same certificate recipe (apex+wildcard, one random 3-letter subdomain+wildcard), 3 first certificates within 26 min, all in one NRD week."),
    "C42b83c2f": ("pure", "7 Vercel deployments of one account's project (`pay8-2v-…-ekontetevi-gmailcom.vercel.app`), all on Phishing.Database."),
    "C80e3f08b": ("impure (same technique, different hosts)", "`accounts.google.<host>` on 7 unrelated registered domains (`.eu.org`, `.ch`, `.cn`, `us.kg`, …): a phishing-kit naming habit, likely several operators or one phishing-as-a-service. All flagged or listed, but \"one maker\" isn't shown."),
    "C04fdbd7a": ("plausible", "`google-site-verification<token>` registered in 3 endings in one NRD week: automated, one maker likely."),
    "C1ca365e6": ("plausible", "`jp-google` bought in 4 endings in one NRD week (a single registrant's multi-TLD buy; RDAP would confirm)."),
    "C5bf644cc": ("plausible", "`googlenewsblog` in 4 endings, one NRD week."),
    "Cd633b363": ("plausible", "`hellogoogle` in 4 endings, one NRD week."),
    "C64aa61bf": ("plausible", "`kr-google` in 3 endings, one NRD week (and probably the `jp-google` maker too: the radar keeps them apart, an under-merge)."),
    "C24d2fc30": ("pure", "`ranking-googleads-gacordong{1,2,3,6}.pages.dev`: one Cloudflare Pages account's naming, seen live."),
}


def main() -> Path:
    r = json.loads((REPO / "data/campaigns/radar.json").read_text(encoding="utf-8"))
    conf = json.loads((REPO / "docs/eval/p13-conformal.json").read_text(encoding="utf-8"))
    st = r["stats"]
    by = {c["id"]: c for c in r["campaigns"]}
    L = ["# P13 Campaign Radar (C18) + the conformal review line", "",
         f"**Generated by `bench/p13_report.py`** from `data/campaigns/radar.json` (run {r['generated_at']}) and "
         "`docs/eval/p13-conformal.json`. Names only: nothing was visited. CT facts come from the cache (`data/certs/ct/`).", "",
         "## 1. From raw input to campaigns", "",
         "| Input | Names judged by the brain | Flagged |", "|---|---|---|"]
    for i in r.get("inputs", []):
        L.append(f"| {i['source']} | {i.get('names', '-') if isinstance(i.get('names'), str) else format(i.get('names', 0), ',') if i.get('names') else '(already judged: live flags + watch list)'} | "
                 f"{i['flagged']:,}{' + ' + format(i['watchlist'], ',') + ' sleepers' if i.get('watchlist') else ''} |")
    L += ["", f"**{st['domains']:,} flagged domains → {st['campaigns']} campaigns ({st['in_campaigns']} domains).** "
          f"Links used: {', '.join(f'{k} {v}' for k, v in st['edges_by_type'].items())}. "
          f"Certificate recipes available for {st['with_recipe']} domains (CT cache only).", "",
          "**Done-when checks:**", ""]
    ech = next((c for c in r["campaigns"] if "in-echallan.online" in c["members_ids"]), None)
    ip = next((c for c in r["campaigns"] if "atxxycp.top" in c["members_ids"]), None)
    L.append(f"- e-Challan campaign: **{'found' if ech else 'NOT found'}** from the raw NRD snapshot"
             + (f": {ech['size']} domains, links {', '.join(ech['links'])}, first certificates "
                f"{ech['recipe']['first_cert']} → {ech['recipe']['last_cert']}." if ech else "."))
    L.append(f"- India Post `.top` campaign: **{'found' if ip else 'NOT found'}** from raw Phishing.Database"
             + (f": {ip['size']} domains, template `{ip['templates'][0]}`." if ip else "."))
    L += ["", "## 2. Hand-check of the top 10 (purity)", "",
          "| # | Campaign | Size | Links | Template | Verdict | Why |", "|---|---|---|---|---|---|---|"]
    pure = 0
    for n, c in enumerate(r["campaigns"][:10], 1):
        v, why = HANDCHECK.get(c["id"], ("not checked", "new since the hand-check: re-check"))
        pure += v.startswith("pure") or v.startswith("plausible")
        L.append(f"| {n} | {', '.join(c['brands'])} | {c['size']} | {', '.join(c['links'])} | `{(c['templates'] or ['-'])[0]}` | **{v}** | {why} |")
    L += ["", f"**{pure} of 10 coherent** (pure or plausibly one maker); only the e-Challan campaign is *proven* one operator "
          "(the certificate recipe). The rest are naming habits: the cards say \"naming habit only\", and C18 stays weak.", "",
          "## 3. The split-conformal review line", "",
          f"- Calibration: P3 `dev` look-alikes, n = {conf['calibration']['n']:,}, alpha = {conf['alpha']}, "
          f"k = {conf['calibration']['k']} → **tau = {conf['calibration']['tau']}** (`fusion.REVIEW_TAU`).",
          "- Guarantee (exchangeability): a new look-alike scores below tau with probability ≤ 5%.", "",
          "| Set | n | Flagged now | Missed now | Below tau among flagged | Missed rate if tau were a BENIGN line |",
          "|---|---|---|---|---|---|"]
    for k in ("test_lookalikes", "test_real", "pdb_india_slice"):
        x = conf[k]
        L.append(f"| {k} | {x['n']:,} | {x['flagged']:,} | {x['missed_now']} | {x['would_drop']} | {x['missed_rate_with_tau'] * 100:.1f}% |")
    lv = conf.get("live_flags")
    L += ["", "**Decision: tau splits the NEEDS REVIEW queue, it doesn't move the BENIGN line.** As a BENIGN line it would "
          f"drop {conf['test_lookalikes']['would_drop']} of the gate's test look-alikes (and `sbi.mx` from `test_real`), and "
          "the no-degradation gate forbids any drop. So a brand-signal name at risk ≥ tau is NEEDS REVIEW with confidence "
          "**medium**, below tau **low**, and the trace says which side of the line it is on. The measured missed rate "
          f"below the line ({conf['test_lookalikes']['missed_rate_with_tau'] * 100:.1f}% of test look-alikes, "
          f"{conf['test_real']['missed_rate_with_tau'] * 100:.1f}% of real phishing) stays inside the 5% bound.", ""]
    if lv:
        L += [f"Live flags (P12 store): {lv['would_clear']} of {lv['n']} fall below the line, mostly one-edit typos of short "
              "names: " + ", ".join(f"`{e}`" for e in lv["examples"][:8]) + ".", ""]
    L += ["## 4. Gate", "", "`bench/regress.py` passes after P13: arena unchanged, genuine 97/98, the India slice unchanged, "
          "speed within budget (C18 adds evidence, never a label; the review line changes confidence, never a label).", "",
          "## 5. Honest limits", "",
          "- **A naming habit isn't proof of one operator.** Only certificate links (shared certificate, same recipe in a "
          "short window) say \"one operator\"; RDAP/registrant and name-server edges were cut in the trim.",
          "- **Recipes need CT records**, and lookups are capped: only cached domains get a recipe (here: the e-Challan five "
          "and a few live catches).",
          "- **Under-merging:** `jp-google` and `kr-google` are probably one maker but stay two campaigns (different literal).",
          "- **Kit habits across hosts** (`accounts.google.<host>`) join different operators; the card says \"naming habit only\".", ""]
    out = REPO / "docs/eval/p13-campaigns.md"
    out.write_text("\n".join(L), encoding="utf-8")
    return out


if __name__ == "__main__":
    sys.stdout.write(f"wrote {main()}\n")
