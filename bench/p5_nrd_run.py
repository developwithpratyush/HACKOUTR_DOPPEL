"""P5: the brain on the full hagezi NRD 7-day snapshot (2.34M real newly registered names). Names only.

    python bench/p5_nrd_run.py [--workers 20] [--limit N]

Writes docs/eval/p5-nrd-run.{md,json}: throughput (one core, and the process pool), labels, the stage each
name reached, flagged names per brand and trick, and the top names by risk (for the hand check in
docs/eval/p5-nrd-handcheck.md). Safety: nothing is fetched. The Page Probe only reads local fixtures, so
every NRD name is "not probed" and a flag means NEEDS REVIEW, never PHISHING.
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from collections import Counter, defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

from doppel.brain.scan import scan  # noqa: E402

NRD = REPO / "data" / "raw" / "nrd" / "nrd7.txt"
OUT = REPO / "docs" / "eval"
KEEP = ("phishing", "sleeper", "needs_review", "genuine")


def names(limit: int | None = None) -> list[str]:
    out = []
    with NRD.open(encoding="utf-8") as f:
        for line in f:
            d = line.strip()
            if d and not d.startswith("#"):
                out.append(d)
                if limit and len(out) >= limit:
                    break
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--workers", type=int, default=20)
    ap.add_argument("--limit", type=int, default=None)
    ap.add_argument("--sample", type=int, default=20_000, help="names for the one-core throughput figure")
    a = ap.parse_args()
    all_names = names(a.limit)
    print(f"{len(all_names):,} names", flush=True)

    # one core, on an evenly spread sample
    step = max(1, len(all_names) // a.sample)
    sample = all_names[::step][: a.sample]
    _, s1 = scan(sample, "nrd_snapshot", workers=1, keep_labels=KEEP)
    one_core = round(len(sample) / (s1["elapsed_ms"] / 1000), 1)
    print(f"one core: {one_core:,}/s on {len(sample):,} names", flush=True)

    verdicts, stats = scan(all_names, "nrd_snapshot", workers=a.workers, keep_labels=KEEP, chunksize=512,
                           on_progress=lambda n: print(f"  {n:,}", flush=True))
    pool_rate = round(stats["total"] / (stats["elapsed_ms"] / 1000), 1)
    flagged = [v for v in verdicts if v["label"] != "genuine"]
    per_brand = Counter((v["target_brand"] or {}).get("id", "(no brand)") for v in flagged)
    per_trick: dict[str, Counter] = defaultdict(Counter)
    for v in flagged:
        tricks = [e["finding"] for e in v["evidence"] if e["tool"] == "trick_detector" and e["criterion"] == "C5"
                  and e["points_to"] == "phishing"] or ["(name evidence only)"]
        for t in tricks:
            per_trick[(v["target_brand"] or {}).get("id", "(no brand)")][t] += 1
    top = sorted(flagged, key=lambda v: (-v["risk_score"], v["domain"]))
    rows = [{"domain": v["domain"], "display": v["input"]["display"], "label": v["label"], "risk": v["risk_score"],
             "brand": (v["target_brand"] or {}).get("id"), "closeness": v["closeness"],
             "tricks": [e["finding"] for e in v["evidence"] if e["tool"] == "trick_detector" and e["criterion"] == "C5"
                        and e["points_to"] == "phishing"], "reason": v["reason"]} for v in top]
    genuine = sorted(v["domain"] for v in verdicts if v["label"] == "genuine")
    summary = {"generated": time.strftime("%Y-%m-%d"), "names": stats["total"], "errors": stats["errors"],
               "error_samples": stats["error_samples"][:10], "workers": a.workers,
               "one_core_per_s": one_core, "pool_per_s": pool_rate, "elapsed_s": round(stats["elapsed_ms"] / 1000, 1),
               "by_label": stats["by_label"], "reached_stage": stats["reached_stage"], "flagged": len(flagged),
               "flagged_per_brand": dict(per_brand.most_common()),
               "tricks_per_brand": {b: dict(c.most_common()) for b, c in per_trick.items()},
               "genuine": genuine, "flagged_ranked": rows}
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "p5-nrd-run.json").write_text(json.dumps(summary, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    write_md(summary, OUT / "p5-nrd-run.md")
    print(json.dumps({k: summary[k] for k in ("names", "errors", "one_core_per_s", "pool_per_s", "elapsed_s",
                                             "by_label", "reached_stage", "flagged_per_brand")}, indent=1))


def write_md(s: dict, path: Path) -> None:
    lines = [
        "# P5: the brain on 2.34 million real new domains (hagezi NRD, 7 days)",
        "",
        f"Generated by `python bench/p5_nrd_run.py` on {s['generated']}. **Rendered from `p5-nrd-run.json`; don't "
        "edit by hand.** Hand check of the top names: `p5-nrd-handcheck.md`.",
        "",
        "**Names only.** Nothing was fetched: the Page Probe reads local fixtures only, so every NRD name is "
        "\"not probed\" and a flagged name is NEEDS REVIEW (ranked by risk), never PHISHING. The snapshot is the "
        "P1-pinned `nrd7.txt` (hagezi/nrd @ b9bd225).",
        "",
        "## Speed",
        "",
        f"- **{s['names']:,} names in {s['elapsed_s']:,} s** with {s['workers']} worker processes: "
        f"**{s['pool_per_s']:,} names/s**.",
        f"- One core: **{s['one_core_per_s']:,} names/s** (full brain: Quick for every name, Standard for brand "
        "signals, counterfactual for flagged names).",
        f"- {s['errors']:,} inputs weren't usable domains (e.g. "
        + ", ".join(f"`{e['input']}`" for e in s["error_samples"][:3]) + ").",
        "",
        "## Labels and stages",
        "",
        "| Label | Names |",
        "|---|---|",
        *[f"| {k} | {v:,} |" for k, v in sorted(s["by_label"].items(), key=lambda kv: -kv[1])],
        "",
        "| Last stage reached | Names |",
        "|---|---|",
        *[f"| {k} | {v:,} |" for k, v in sorted(s["reached_stage"].items(), key=lambda kv: -kv[1])],
        "",
        f"## Flagged per brand ({s['flagged']:,} names)",
        "",
        "| Brand | Flagged | Tricks (a name can carry several) |",
        "|---|---|---|",
        *[f"| {b} | {n:,} | " + ", ".join(f"{t} {c}" for t, c in s["tricks_per_brand"].get(b, {}).items()) + " |"
          for b, n in s["flagged_per_brand"].items()],
        "",
        f"Genuine family names found among the new registrations: {', '.join(f'`{g}`' for g in s['genuine']) or 'none'}.",
        "",
        "## Top 40 by risk",
        "",
        "| # | Name | Brand | Risk | Closeness | Tricks |",
        "|---|---|---|---|---|---|",
        *[f"| {i} | `{r['display']}` | {r['brand']} | {r['risk']:.3f} | {r['closeness']} | {', '.join(r['tricks'])} |"
          for i, r in enumerate(s["flagged_ranked"][:40], 1)],
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
