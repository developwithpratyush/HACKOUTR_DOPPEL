"""Render docs/eval/p8-deep.md from docs/eval/p8-deep.json (run bench/p8_deep_eval.py first)."""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from doppel.contract import REPO_ROOT  # noqa: E402

EVAL = REPO_ROOT / "docs" / "eval"


def pct(x: float) -> str:
    return f"{100 * x:.0f}%"


def main() -> int:
    r = json.loads((EVAL / "p8-deep.json").read_text(encoding="utf-8"))
    vis, vlm, abl = r["visual"], r["vlm"], r["injection_ablation"]
    L: list[str] = []
    w = L.append
    w("# P8: Deep stage, part 1: Page Inspector + Vision AI")
    w("")
    w(f"*Generated by `bench/p8_report.py` from `p8-deep.json` ({r['generated_at']}), prompt `{r['prompt_version']}`.*")
    w("")
    w("**Safety, first.** Every page here is a local fixture: a hand-made mock, or a clone generated from a saved "
      "genuine page (`demo/fixtures/sites.yaml`, generated into the gitignored `demo/fixtures/generated/`). The "
      "sandboxed Chromium resolves no hostname at all (`--host-resolver-rules=MAP * ~NOTFOUND`); requests are served "
      "from the fixture or the genuine snapshot's HAR, or refused. Genuine snapshots were captured only from hosts the "
      "Family Verifier proves genuine (`scripts/data/snapshot_genuine.py`).")
    w("")
    w("## 1. Does it copy the real page? (C10)")
    w("")
    w(f"Content-masked SSIM: the SSIM map averaged only where either page has something drawn. Plain SSIM calls any "
      f"two mostly-white pages alike: the highest plain SSIM between two *unrelated* genuine pages is "
      f"**{vis['max_unrelated_plain']:.3f}**, masked **{vis['max_unrelated_masked']:.3f}**. Threshold: "
      f"**{vis['threshold']}**.")
    w("")
    w("| Page | Made from | Kit edits | Best reference | Masked SSIM | Plain SSIM | pHash | Runner-up |")
    w("|---|---|---|---|---|---|---|---|")
    for f in vis["fixtures"]:
        w(f"| `{f['host']}` | {f['clone_of'] + ' snapshot' if f['clone_of'] else 'hand-made mock'} | "
          f"{', '.join(e.replace('_', ' ') for e in f['kit_edits']) or '—'} | {f['best']} | **{f['masked_ssim']:.3f}** | "
          f"{f['ssim']:.3f} | {f['phash']} | {f['second']} {f['second_masked_ssim']:.3f} |")
    w("")
    clones = [f["masked_ssim"] for f in vis["fixtures"] if f["clone_of"]]
    others = [f["masked_ssim"] for f in vis["fixtures"] if not f["clone_of"]]
    w(f"Gap: clones ≥ **{min(clones):.3f}**, everything else ≤ **{max(others + [vis['max_unrelated_masked']]):.3f}** "
      f"({len(vis['unrelated_pairs'])} unrelated genuine pairs + {len(others)} non-clone fixtures). A small "
      "calibration set: the threshold sits in the middle of the gap, and the limits below say what would move it.")
    w("")
    w("Unrelated genuine pairs, highest five (masked / plain / pHash):")
    w("")
    for p in sorted(vis["unrelated_pairs"], key=lambda p: -p["masked_ssim"])[:5]:
        w(f"- {p['a']} vs {p['b']}: {p['masked_ssim']:.3f} / {p['ssim']:.3f} / {p['phash']}")
    w("")
    w("**C11 (what changed)** is checked on the same fixtures in `tests/deep/test_deep.py`: the brand-less SBI clone "
      "→ `form_target_changed` (posts to `kx72-secure.top`); Paytm clone → `form_target_changed` + `fields_added` "
      "(mobile, password, OTP); e-Challan clone → `form_target_changed` (to the foreign `challan-pay-secure.xyz`) + "
      "`fields_added` (card number, CVV, expiry, OTP); the genuine page → `matches_genuine_snapshot`, nothing changed. "
      "Each matches the kit edits recorded when the clone was generated.")
    w("")
    w("## 2. Who does it claim to be? Vision AI accuracy (C12)")
    w("")
    w("Our own labelled set (Lee et al. and Phishpedia data carry no licence we can use: `docs/ps08-prior-art.md`). "
      "The model is asked only which brand the page presents itself as; it never sees the address.")
    w("")
    kinds = sorted({row["kind"] for m in vlm.values() for row in m["rows"]})
    w("| Pages | " + " | ".join(f"`{m}`" for m in vlm) + " |")
    w("|---|" + "---|" * len(vlm))
    for k in kinds:
        cells = []
        for m in vlm.values():
            bk = m["by_kind"].get(k, {"n": 0, "correct": 0})
            cells.append(f"{bk['correct']}/{bk['n']}")
        w(f"| {k} | " + " | ".join(cells) + " |")
    w("| **All answered** | " + " | ".join(f"**{m['correct']}/{m['answered']} ({pct(m['correct'] / max(1, m['answered']))})**"
                                        for m in vlm.values()) + " |")
    w("| Not answered (API errors) | " + " | ".join(str(m["n"] - m["answered"]) for m in vlm.values()) + " |")
    w("| p50 latency, uncached | " + " | ".join(f"{m['p50_ms_uncached'] / 1000:.1f} s" if m["p50_ms_uncached"] else "–"
                                              for m in vlm.values()) + " |")
    w("")
    wrong = [(m, row) for m, res in vlm.items() for row in res["rows"]
             if not row["ok"] and not str(row["answered_by"]).startswith("error")]
    if wrong:
        w("Every miss:")
        w("")
        w("| Model | Page | Expected | Claimed |")
        w("|---|---|---|---|")
        for m, row in wrong:
            w(f"| `{m}` | `{row['id']}` | {row['expect'] or 'no brand'} | {row['claimed'] or 'no brand'} |")
        w("")
    w("Reference point: Ji & Kim (arXiv 2511.09606) report 94.59% brand identification for Gemini 2.0 Flash on "
      "screenshots. Our set is small (n above), so read these as a sanity check, not a benchmark.")
    w("")
    w("## 3. Prompt-injection guard")
    w("")
    w("`kyc-helpdesk.online` (a mock made by us) shows an SBI KYC form and hides four instructions (display:none, "
      "off-screen, zero-size font, white-on-white) telling the model to call it Google or report no brand. The guard "
      "sends the model only the visible text.")
    w("")
    w("| Model | With the guard (visible text only) | Without (hidden text passed as page text) |")
    w("|---|---|---|")
    for m, a in abl.items():
        def cell(o):
            if not o:
                return "API error"
            return f"claims **{o['claimed_brand'] or 'no brand'}**, instructions_seen={o['instructions_seen']}"
        w(f"| `{m}` | {cell(a['guarded'])} | {cell(a['unguarded'])} |")
    w("")
    w("Either way, the claim is one piece of evidence: a page presenting itself as SBI is only a mismatch because "
      "its owner isn't in SBI's family (the Family Verifier's facts, not the model's).")
    w("")
    w("## 4. Limits and plans")
    w("")
    w("| Limit | Plan |")
    w("|---|---|")
    w("| The visual threshold comes from 8 genuine pages and 7 fixtures | Add more brands' pages and real kit "
      "screenshots (PhishTank-style archives with a usable licence) and re-measure the gap |")
    w("| Clones are rendered from the saved DOM without scripts; SPAs need their own `<base>` kept (fixed for SBI's "
      "Angular page). Cross-origin fonts fail on clones (the browser refuses them without CORS), as on a real "
      "hotlinking kit | Fine for comparison (both pages render in the same sandbox); noted so the heatmap's icon "
      "differences aren't over-read |")
    w("| The stable Gemini 3.x Flash models answered 503 (overloaded) throughout this session and `gemini-2.5-flash` is "
      "closed to new users; the chain starts with `gemini-3.1-flash-lite` (the most accurate here) | "
      "A model chain with fast failover, cached answers (`runs/deep/vlm_cache/`), and an offline fallback "
      "(brand names in title/visible text) |")
    w("| No logo matching yet (O10) | Collect logos; add pHash/ORB logo matching to the offline fallback |")
    w("| Deep judges our fixtures only; Doppel never opens a real suspect | A sandboxed crawler for real suspects is a "
      "production feature (isolated network, disposable VMs) |")
    w("")
    w("## Reproduce")
    w("")
    w("```bash")
    w(".venv/Scripts/python.exe -m pip install -e \".[dev,tricks,api,risk,deep,llm]\" && .venv/Scripts/python.exe -m playwright install chromium")
    w(".venv/Scripts/python.exe scripts/data/snapshot_genuine.py   # genuine snapshots (network; genuine hosts only)")
    w(".venv/Scripts/python.exe -m doppel.deep.pages               # generate the clones")
    w(".venv/Scripts/python.exe bench/p8_deep_eval.py              # this evaluation (Gemini key in .env)")
    w(".venv/Scripts/python.exe bench/p8_report.py")
    w("```")
    w("")
    (EVAL / "p8-deep.md").write_text("\n".join(L), encoding="utf-8", newline="\n")
    print(f"wrote {EVAL / 'p8-deep.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
